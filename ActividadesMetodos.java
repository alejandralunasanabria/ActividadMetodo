public class ActividadesMetodos {

    // Método que calcula y retorna la suma de dos números enteros
    public static int sumar(int num1, int num2) {
        int resultado = num1 + num2;
        return resultado;
    }

    public static void main(String[] args) {
        // Llamada al método sumar e impresión del resultado en consola
        System.out.println(sumar(7, 8)); 
    }
}